// Project the same geometry used by the HTML screen layer into standalone SVGs.
// CSS applies rotations from right to left, around the artboard center.
// Solve a projective mapping from four measured corners.
function homography(source, target) {
  const rows = source.flatMap(([x,y],i) => {
    const [u,v] = target[i];
    return [[x,y,1,0,0,0,-u*x,-u*y,u],[0,0,0,x,y,1,-v*x,-v*y,v]];
  });
  for(let col=0;col<8;col++) {
    let pivot=col;
    for(let r=col+1;r<8;r++) if(Math.abs(rows[r][col])>Math.abs(rows[pivot][col])) pivot=r;
    [rows[col],rows[pivot]]=[rows[pivot],rows[col]];
    const div=rows[col][col]; rows[col]=rows[col].map(v=>v/div);
    for(let r=0;r<8;r++) if(r!==col) {const f=rows[r][col];rows[r]=rows[r].map((v,i)=>v-f*rows[col][i]);}
  }
  return rows.map(r=>r[8]);
}
const corners = [[514,39],[934,39],[934,921],[514,921]];
// Extended straight edges of the supplied HM15 reference, before rounded corners.
const topCorners = [[816,391],[1168,190],[1694,864],[1327,1067]]
  .map(([x,y])=>[724+(x-1255)*0.9,440+(y-628.5)*0.9]);
const topMapping = homography(corners, topCorners);
// SOM25: lower camera, top end to the upper right, bottom end to the lower left.
const topLowMapping = homography(corners, [[1210,246],[1584,482],[815,1055],[448,790]]
  .map(([x,y])=>[724+(x-1016)*0.9,435+(y-650.5)*0.9]));
const variants = { front: [0, 0, 0], top: [30, 0, -36], right: [0, 28, 0], left: [0, -28, 0], "top-low": [0, 0, 0] };
const root = new URL('../', import.meta.url);
const catalog = {};
for (const [variant, angles] of Object.entries(variants)) {
  const [rx, ry, rz] = angles.map(a => a * Math.PI / 180);
  const project = (x, y, z) => {
    if(variant === 'top' || variant === 'top-low') {
      const [a,b,c,d,e,f,g,h] = variant === 'top' ? topMapping : topLowMapping;
      const w=g*x+h*y+1;
      const dx=variant === 'top' ? 0.25 : 0.08;
      const dy=variant === 'top' ? 0.65 : 1.2;
      return `${((a*x+b*y+c)/w+z*dx).toFixed(4)},${((d*x+e*y+f)/w-z*dy).toFixed(4)}`;
    }
    x -= 724; y -= 480;
    [y, z] = [y * Math.cos(rx) - z * Math.sin(rx), y * Math.sin(rx) + z * Math.cos(rx)];
    [x, z] = [x * Math.cos(ry) + z * Math.sin(ry), -x * Math.sin(ry) + z * Math.cos(ry)];
    [x, y] = [x * Math.cos(rz) - y * Math.sin(rz), x * Math.sin(rz) + y * Math.cos(rz)];
    const scale = 2606.4 / (2606.4 - z);
    return `${(724 + x * scale).toFixed(4)},${(480 + y * scale).toFixed(4)}`;
  };
  const rect = (x, y, w, h, r, fill, z = 0) => {
    const points = [];
    for (const [cx, cy, start] of [[x+w-r,y+r,-90],[x+w-r,y+h-r,0],[x+r,y+h-r,90],[x+r,y+r,180]]) {
      for(let i=0;i<=64;i++) {
        const a=(start+i*90/64)*Math.PI/180;
        points.push(project(cx+r*Math.cos(a),cy+r*Math.sin(a),z));
      }
    }
    return `<path fill="${fill}" d="M${points.join(' L')} Z"/>`;
  };
  const paths = ['<rect width="1448" height="960" fill="#dadbde"/>'];
  // Top view rests on a floor: a small cast shadow and a tighter contact shadow.
  if (variant === 'top' || variant === 'top-low') {
    paths.push(`<g transform="translate(9 17)" opacity="0.17">${rect(514,39,420,882,59,'#353c44',-17.376)}</g>`);
    paths.push(`<g transform="translate(3 5)" opacity="0.12">${rect(514,39,420,882,59,'#353c44',-17.376)}</g>`);
  }
  if(variant !== 'front') for(let depth=8;depth>=1;depth--) paths.push(rect(514,39,420,882,59,(variant === 'top' || variant === 'top-low') ? (depth>4?'#858e96':'#b5bdc4') : (depth>4?'#b5bcc2':'#c8cdd1'),-depth*2.172));
  paths.push(rect(514,39,420,882,59,'#b7bdc2'),rect(517,41,414,878,57,'#1c2023'));
  for(const [x,y,w,h] of [[510,194,4,37],[510,258,4,65],[510,342,4,65],[934,281,4,94]]) paths.push(rect(x,y,w,h,2,'#aeb5bb'));
  paths.push(rect(526,51,396,858,46,'#fafafa'));
  const src = `/mockups/phone-studio-${variant}.svg`;
  writeFileSync(fileURLToPath(new URL(`public${src}`,root)),`<svg xmlns="http://www.w3.org/2000/svg" width="1448" height="960" viewBox="0 0 1448 960"><title>Studio 01 · Phone · ${variant}</title>\n${paths.join('\n')}\n</svg>\n`);
  const [a,b,c,d,e,f,g,h] = homography(corners,corners.map(([x,y])=>project(x,y,0).split(',').map(Number)));
  catalog[variant] = { src: variant === "top" || variant === "top-low" ? `${src}?v=raised-30` : src, transform: `matrix3d(${[a,d,0,g,b,e,0,h,0,0,1,0,c,f,0,1].join(',')})` };
}
writeFileSync(fileURLToPath(new URL('src/lib/phone-mockup-geometry.ts',root)),`// Generated by scripts/generate-phone-mockups.mjs. Keep SVG and media transforms in sync.\nexport const PHONE_VARIANTS = ${JSON.stringify(catalog,null,2)} as const;\n`);
